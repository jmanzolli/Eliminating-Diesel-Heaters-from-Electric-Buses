def load(fn):
    return json.load(open(os.path.join(V11, fn)))


def runs_of(fn):
    return {r["label"]: r for r in load(fn)["runs"]}


def tight_runs(case):
    """v11b records of one case (base, cap_D1, var_hp, batt_50, ...), by label."""
    fn = os.path.join(TIGHT, f"{case.replace('.', '_')}.json")
    if not os.path.exists(fn):
        return {}
    return {r["label"]: r for r in json.load(open(fn))["runs"]}


def k(v, nd=1):
    return f"{v / 1e3:,.{nd}f}"


def signature(r):
    """First-stage design: fleet by class, chargers, grid tiers."""
    return json.dumps([sorted(r["fleet"].items()), sorted(r["chargers"].items()),
                       sorted((s, v) for s, v in r["grid_kW"].items() if v)])


def charger_text(r):
    return ", ".join(f"{s}:{n}x{p}" if n > 1 else f"{s}:{p}"
                     for s, n, p in sorted((c.split(":")[0], v, c.split(":")[1])
                                           for c, v in r["chargers"].items()))


out, md = {}, ["# v11 campaign: results", "",
               "Generated by `postprocess_v11.py` from `v11_results/`. Costs in "
               "kCAD/yr unless noted. UB = incumbent, LB = solver lower bound.", ""]

# =================================================================== corridor
camp = load("campaign_v11_results.json")
C = {r["label"]: r for r in camp["runs"]}
FULLSET = re.compile(r"^(econ_lam0|policy_lam100|eps_|lam_|bp_lam_)")
designs = {l: r for l, r in C.items() if FULLSET.match(l) and "F1" in r}
# v11b corridor records, labelled t_<case>_<label>; all are feasible full-set designs
TB = {f"t_{case}_{l}": r for case in ("base", "cap_D1", "cap_D2", "cap_D3")
      for l, r in tight_runs(case).items() if "F1" in r}
designs.update(TB)
# cap bounds: v11 cap runs and the v11b free re-solves under a cap (never fixed-design bounds)
cap_runs = {l: r for l, r in designs.items()
            if l.startswith("eps_") or (l.startswith("t_cap_") and l.endswith("_free"))}
lam_runs = {l: r for l, r in designs.items()
            if (l.startswith("lam_") or l.startswith("bp_lam_") or l == "policy_lam100")}

UB0 = min(r["F1"] for r in designs.values())
LB0 = max([C["econ_lam0"]["lb"]] + ([TB["t_base_free"]["lb"]] if "t_base_free" in TB else []))
# baseline: lowest-emission plan within LEX_TOL of the best known cost
ties = sorted(({"label": l, "co2_t": r["co2_t"], "F1": r["F1"]} for l, r in designs.items()
               if r["F1"] <= UB0 + LEX_TOL), key=lambda t: (t["co2_t"], t["F1"]))
base_lbl = ties[0]["label"]
BASE = designs[base_lbl]
assert base_lbl == camp["baseline_ties"]["plans"][0]["label"], \
    f"baseline changed: {base_lbl} vs {camp['baseline_ties']['plans'][0]['label']}"


def lb_cap(E):
    """Certified lower bound on the minimum cost with emissions <= E."""
    cands = [LB0]
    for r in cap_runs.values():
        if r["eps"] >= E - 1e-9 and "lb" in r:
            cands.append(r["lb"])
    for r in lam_runs.values():
        if "lb" in r and r["lam"] > 0:
            cands.append(r["lb"] - r["lam"] * E)
    return max(cands)


def certified(r):
    return (max(0.0, lb_cap(r["co2_t"]) - UB0), r["F1"] - LB0)


# lower convex hull of (emissions, cost) over all designs, from the baseline down
# (plans above the baseline's emissions are cost ties of it or dominated)
pts = sorted(((r["co2_t"], r["F1"], l) for l, r in designs.items()), key=lambda p: (p[0], p[1]))
pts_h = [p for p in pts if p[0] <= BASE["co2_t"] + 1e-9]
# Pareto set: no other point with lower-or-equal emissions and lower cost
pareto = [p for p in pts_h if not any(q[0] <= p[0] + 1e-9 and q[1] < p[1] - 1e-6 and q != p
                                      for q in pts_h)]
pareto.sort(key=lambda p: -p[0])          # from high emissions to zero
hull = []
for p in pareto:
    while len(hull) >= 2:
        (e1, c1, _), (e2, c2, _) = hull[-2], hull[-1]
        # keep convex from below: slope must increase as emissions fall
        s12 = (c2 - c1) / (e1 - e2)
        s23 = (p[1] - c2) / (e2 - p[0])
        if s23 <= s12 + 1e-9:
            hull.pop()
        else:
            break
    hull.append(p)
segments = []
for (e1, c1, l1), (e2, c2, l2) in zip(hull, hull[1:]):
    segments.append({"from": l1, "to": l2, "d_cost": c2 - c1, "d_co2": e1 - e2,
                     "price": (c2 - c1) / (e1 - e2)})

# design ladder D0-D4, fixed by equipment (ladder_v11.json, chosen in v11 as the
# hull vertices with distinct first stages): each rung is the cheapest recorded
# operation of that equipment at or below the rung's emissions
