       f". Reported baseline: {base_lbl} ({BASE['co2_t']:.1f} t, {BASE['n_ffh']} heaters).",
       f"- Caps were set as fractions of {camp['caps_basis_co2_t']} t (econ_lam0 record); "
       "in tonnes: " + ", ".join(f"{l} {r['eps']:.2f} t" for l, r in sorted(
           cap_runs.items(), key=lambda x: -x[1]["eps"])) + ".", "",
       "All full-set corridor designs:", "",
       "| Run | Cost | LB | Gap | CO2 (t) | Heaters | Ext. batt. | Increment, tabulated | "
