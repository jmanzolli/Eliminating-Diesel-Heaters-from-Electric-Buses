for kk in ("D1", "D2", "D3", "D4"):
    e_max = LADDER[kk]["co2_t"] + 0.01
    cand = [(r["F1"], l) for l, r in designs.items()
            if signature(r) == signature(LADDER[kk]) and r["co2_t"] <= e_max]
    ladder.append(min(cand)[1])
assert signature(BASE) == signature(LADDER["D0"]), "baseline equipment is not D0"
hull_lbls = {l for _, _, l in hull}
for kk, l in zip(("D0", "D1", "D2", "D3", "D4"), ladder):
    if l not in hull_lbls:
        print(f"note: ladder rung {kk} ({l}) is not a hull vertex")

# certified statements on the carbon price that makes the heater-free design optimal
hf = designs[ladder[-1]]
LB_HF = lb_cap(0.0)            # no heater-free design costs less than this
not_optimal_at = [r["lam"] for r in lam_runs.values()
                  if r["lam"] > 0 and r["obj"] < LB_HF - 1e-6]
switch_lb = max(not_optimal_at) if not_optimal_at else 0.0

