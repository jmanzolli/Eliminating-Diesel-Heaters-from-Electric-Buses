def case_summary(case, extra_econ=None, extra_hf=None):
    """Cost-only summary of one v11b case.

    best    cheapest recorded plan (fixed-design evaluations, free re-solve,
            optional v11 cost-only run of the same case)
    lb      best valid bound on the case's minimum cost (free re-solves only)
    fix     ladder designs with the first stage fixed: cost and design bound,
            or the Gurobi status when no operation was found (3 = infeasible)
    hf_*    heater-free plans: best recorded cost; bound only when a v11
            heater-free (eps_0.00) re-solve of the case exists
    """
    T = tight_runs(case)
    if not T:
        return None
    recs = [(l, r) for l, r in T.items() if "F1" in r]
    if extra_econ and "F1" in extra_econ:
        recs.append(("v11_econ_lam0", extra_econ))
    bl, br = min(recs, key=lambda x: x[1]["F1"])
    lbs = [r["lb"] for l, r in T.items() if l == "free" and "lb" in r]
    if extra_econ and "lb" in extra_econ:
        lbs.append(extra_econ["lb"])
    lb = max(lbs)
    fix = {}
    for d in DK:
        r = T.get(f"fix_{d}")
        if r is None:
            continue
        fix[d] = ({x: r[x] for x in ("F1", "lb", "co2_t", "n_ffh", "diesel_L")} if "F1" in r
                  else {"status": r.get("status")})
    hf_c = [r for r in [T.get("fix_D4"), extra_hf] if r and "F1" in r]
    hf_ub = min(r["F1"] for r in hf_c) if hf_c else None
    hf_lb = extra_hf["lb"] if extra_hf and "lb" in extra_hf else None
    s = {"best": {x: br[x] for x in ("F1", "co2_t", "n_ffh", "n_ext", "diesel_L", "fleet",
                                     "chargers", "grid_kW")},
         "best_label": bl, "best_design": LSIG.get(signature(br), "other"),
         "lb": lb, "gap": br["F1"] - lb, "fix": fix,
         "infeasible": [d for d in DK if d in fix and fix[d].get("status") == 3],
         "no_solution": [d for d in DK if d in fix and fix[d].get("status") not in (None, 3)
                         and "F1" not in fix[d]]}
    if "D0" in fix and "F1" in fix["D0"]:
        f0 = fix["D0"]
        s.update(d0_excess=f0["F1"] - br["F1"], d0_regret_hi=f0["F1"] - lb,
                 d0_certified_suboptimal=f0["lb"] > br["F1"])
    if hf_ub is not None:
        s.update(hf_ub=hf_ub, premium=hf_ub - br["F1"], premium_hi=hf_ub - lb,
                 premium_lo=(hf_lb - br["F1"]) if hf_lb is not None else None)
    # pairwise ranking of the ladder designs that the design bounds certify
    s["certified_order"] = [(a, b) for a in DK for b in DK if a != b and a in fix and b in fix
                            and "F1" in fix[a] and "F1" in fix[b] and fix[b]["lb"] > fix[a]["F1"]]
    return s


def robust_row(name, s):
    fx = s["fix"]
    cells = []
    for d in DK:
        f = fx.get(d)
        cells.append("n/a" if f is None else (k(f["F1"]) if "F1" in f else
                                               ("infeasible" if f.get("status") == 3 else "none in time")))
    pr = (f"{k(s['premium'])} [{k(s['premium_lo']) if s.get('premium_lo') is not None else '?'}"
          f"-{k(s['premium_hi'])}]" if "premium" in s else "---")
    return (f"| {name} | {k(s['best']['F1'])} | {k(s['lb'])} | {k(s['gap'])} | "
            f"{s['best']['n_ffh']} ({s['best_design']}) | {s['best']['co2_t']:.1f} | "
            + " | ".join(cells) +
            f" | {k(s['d0_regret_hi']) if 'd0_regret_hi' in s else '---'} | {pr} |")


