    so = r["scen_ops"]
    price = r["cost_parts"].get("diesel_cost", 0.0) / r["diesel_L"] if r["diesel_L"] > 0 else 0.0
    return {w: so[w]["electricity_cost"] + price * so[w]["diesel_L"] for w in BANDS}, price
