"""Post-processing of the v11 campaign (run_all_v11.sh, 12-14 Nov 2026).

Reads the result files copied from the server into v11_results/ and writes
v11_results/results_v11.json (for the table and figure scripts) and
v11_results/RESULTS_v11.md (for the authors). No solver.

Why this exists: in v11 most corridor solves stopped at the time limit with
absolute gaps of 10-40 kCAD/yr, larger than the cost differences between
neighbouring frontier points. So
  * the frontier is the lower convex hull of EVERY recorded full-set corridor
    design (cap runs, carbon-price runs, breakpoint re-solves and the
    fixed-design ops passes), not of the cap runs alone: several cap runs
    stopped at incumbents that a carbon-price run beats at lower emissions;
  * every increment is reported with a certified range built from valid
    lower bounds;
  * the baseline is the lowest-emission plan within LEX_TOL of the best known
    cost (core_finish_v9.py v11b, "baseline_ties").

Lower bounds used (all on cost, CAD/yr):
  LB0          min cost, no cap: the econ_lam0 bound.
  LBcap(E)     min cost s.t. emissions <= E: max of
                 - the bound of any cap run with cap >= E (a looser cap
                   cannot cost more), and
                 - LB(lam) - lam*E for any carbon-price run (Lagrangian:
                   cost + lam*e >= LB(lam) for every feasible design).
A design's increment over the baseline lies in [LBcap(e) - UB0, F1 - LB0].

v11b (run_tighten_v11.sh, 15-16 Nov 2026; files in v11b_results/) adds
  * cost-only corridor re-solves: the free problem warm-started from the
    baseline (6 h, 12 threads; a valid LB0) and cost minima capped at the
    emissions of D1-D3 (valid cap bounds), plus the ladder designs evaluated
    with their first stage fixed (feasible points, design-specific bounds);
  * for every variant and sensitivity, cost only: the five ladder designs with
    the first stage fixed, then a free re-solve started from the cheapest;
  * reliability of the reported baseline design itself (policy_lam100_ops).
The ladder is fixed by its equipment (server_v11/ladder_v11.json): each rung
is the cheapest recorded operation of that equipment at or below the rung's
emissions. A bound from a fixed-design solve is never used as a bound on the
free problem.

Usage (from code/): python3 postprocess_v11.py
"""
