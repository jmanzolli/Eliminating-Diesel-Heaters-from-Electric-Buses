def tab_fuelrate():
    """Burner fuel rate scaled with designs and dispatch fixed: diesel and
    emissions scale with the rate, cost moves by the diesel cost difference;
    the frontier is the lower convex hull of the re-priced designs."""
    rows = []
    base = D["D0"]
    for rate in (0.70, 1.00, 1.15):
        pts = []
        for l, r in DES.items():
            dsl = r["cost_parts"].get("diesel_cost", 0.0)
            pts.append((rate * r["co2_t"], r["F1"] + (rate - 1.0) * dsl, l))
        # frontier starts at the reported baseline D0, as in postprocess_v11
        # (cost ties that emit more than D0 are not on it)
        pts = [p for p in pts if p[0] <= rate * DES[base]["co2_t"] + 1e-9]
        par = [p for p in pts if not any(q[0] <= p[0] + 1e-9 and q[1] < p[1] - 1e-6 for q in pts)]
        par.sort(key=lambda p: -p[0])
        hull = []
        for p in par:
            while len(hull) >= 2:
                (e1, c1, _), (e2, c2, _) = hull[-2], hull[-1]
                if (p[1] - c2) / (e2 - p[0]) <= (c2 - c1) / (e1 - e2) + 1e-9:
                    hull.pop()
                else:
                    break
            hull.append(p)
        sl = [(c2 - c1) / (e1 - e2) for (e1, c1, _), (e2, c2, _) in zip(hull, hull[1:])]
        b = DES[base]
        e0, c0 = hull[0][0], hull[0][1]
        avg = (hull[-1][1] - c0) / e0
        rows.append(f"{100 * rate:.0f} & {num(rate * b['diesel_L'])} & {rate * b['co2_t']:.1f} & "
                    f"{sl[0] / 1e3:.2f} & {sl[-1] / 1e3:.2f} & {len(sl)} & {avg / 1e3:.2f} \\\\")
    body = r"""\begin{table*}[pos=tp]
\caption{Burner fuel-rate range of \cite{liu2026zero} applied to the
Route~52 designs, with designs and dispatch held fixed: baseline
diesel and emissions, slopes of the cost--emissions frontier from the
baseline to full electrification, and the average abatement cost.}
\label{tab:supp-fuelrate}
\centering
\small
\setlength{\tabcolsep}{3pt}
\fittab{rrrrrrr@{}}{
\toprule
\textbf{\makecell{Fuel rate\\(\%%\ rated)}} & \textbf{\makecell{Diesel\\(L/yr)}} &
\textbf{\makecell{\COtwo{}\\(t/yr)}} & \textbf{\makecell{First slope\\(kCAD/t)}} &
\textbf{\makecell{Last slope\\(kCAD/t)}} & \textbf{\makecell{Seg-\\ments}} &
\textbf{\makecell{Average\\(kCAD/t)}} \\
\midrule
%s
\bottomrule
}
\end{table*}
""" % "\n".join(rows)
    write("supp_tables", "tab_fuelrate_m2.tex", body)


