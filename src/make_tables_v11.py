def fleet_counts(r):
    f = r["fleet"]
    return (f.get("NF-std-FFH", 0), f.get("NF-std-eOnly", 0),
            f.get("NF-ext-FFH", 0), f.get("NF-ext-eOnly", 0))


def chargers(r, depot):
    """count x kW, grouped by power, depot or terminals."""
    by = {}
    for c, n in r["chargers"].items():
        site, p = c.split(":")
        if (site == "depot") == depot:
            by[int(p)] = by.get(int(p), 0) + n
    if not by:
        return "---"
    return ", ".join(f"{n}$\\times${p}" for p, n in sorted(by.items(), reverse=True))


def control(lbl, r):
    if r.get("eps") is not None and r["eps"] < 1e5 and "_fix_" not in lbl:
        return f"cap {r['eps']:.2f} t"
    if r.get("lam"):
        return f"{r['lam']:,.0f} CAD/t"
    if "_fix_" in lbl:
        return "cost only"
    return "---"


