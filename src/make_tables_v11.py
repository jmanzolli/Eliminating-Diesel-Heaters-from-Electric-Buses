def dlist(ds):
    """D1, D2, D3 -> D1--D3 when consecutive."""
    if not ds:
        return ""
    n = [int(d[1]) for d in ds]
    if len(n) > 2 and n == list(range(n[0], n[-1] + 1)):
        return f"D{n[0]}--D{n[-1]}"
    return ", ".join(ds)


def sens_row(name, r, base_F1):
    b = r["best"]
    nofeas = dlist(r["infeasible"])
    if r["no_solution"]:
        nofeas = "; ".join(x for x in [nofeas, dlist(r["no_solution"]) + "$^{\\dagger}$"] if x)
    prem = (f"{kc(r['premium'])} ($\\le${kc(r['premium_hi'])})" if "premium" in r else "---")
    eq = r["best_design"] if r["best_design"] != "other" else "new"
    return (f"{name} & {kc(b['F1'])} & {(b['F1'] - base_F1) / 1e3:+.1f} & {kc(r['gap'])} & "
            f"{b['n_ffh']} ({eq}) & {b['co2_t']:.1f} & "
            f"{kc(r['d0_regret_hi']) if 'd0_regret_hi' in r else '---'} & {prem} & "
            f"{nofeas or '---'} \\\\")


